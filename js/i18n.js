/** ترجمة + باراميتر {name} */
export function t(key, params) {
  const lang = get('lang') || 'ar';
  let s = (MESSAGES[lang] && MESSAGES[lang][key]) ?? (MESSAGES.en[key] ?? key);
  if (params) Object.keys(params).forEach(p => { s = s.split(`{${p}}`).join(params[p]); });
  return s;
}

/** تطبيق اللغة على [data-i18n] + سمات + html lang/dir */
export function applyI18n() {
  const lang = get('lang') || 'ar';
  const html = document.documentElement;
  html.lang = lang;
  html.dir = lang === 'ar' ? 'rtl' : 'ltr';
  html.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  html.querySelectorAll('[data-i18n-attr]').forEach(el => {
    el.dataset.i18nAttr.split(';').forEach(pair => {
      const [attr, key] = pair.split(':').map(s => s.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    });
  });
}

export function setLang(lang) {
  if (lang !== 'ar' && lang !== 'en') return;
  set({ lang });
}

subscribe(changed => { if (changed.includes('lang')) applyI18n(); });
